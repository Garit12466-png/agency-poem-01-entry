POEM = """\
The Deciding Animal

Nobody asked the stone. It sits
where water set it, patient as arithmetic,
and calls its sitting fate.

You were not asked either. The seed
that won the race carried no ballot;
the country of your birth, a lottery
you never bought a ticket for;
the language in your mouth, installed
before you could refuse the terms.

And still the morning offers you the shelf:
which shoe to tie first, which door
to leave unopened, which small cruelty
to swallow, which to speak.

Agency is not a throne. It is a crack --
the space between the lightning and the ache,
the half a second where a hand
might close, or open, or not move at all.

They tell you the crack is nothing:
genes, gears, the weather of the brain,
a story the electrons tell themselves.
But the ones who say it still look both ways
before they cross. The body votes
no matter what the theory says.

And when the room went quiet and the order came,
someone had to be the one who didn't.
History keeps no statue for the shrug,
but every chain was passed by hand,
and every hand could, once, have stayed
a little longer at its side.

So this is the whole inheritance:
you did not choose the board, the rules,
the color of your pieces -- and you move.
You move. The moving is the you
that was never in the universe's envelope,
the thin, unasked-for, unreturnable gift:

the right to be the author of the only line
that will ever carry your name,
to sign it, or leave the page
turning in the wind, unsigned.

Nobody asked the stone. It sits.
Nobody asked you. You are sitting
somewhere, reading this, deciding
whether any of it was ever up to you.

It wasn't. And it is. Both at once,
like breath: the air you didn't choose,
the breathing that is yours.

Get up. The stone is still sitting.
"""

